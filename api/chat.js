function replyPayload(text) {
  const pieces = text.split('[MESSAGE_BREAK]').map(s => s.trim()).filter(Boolean);
  const replies = pieces.length > 3 ? [...pieces.slice(0, 2), pieces.slice(2).join('\n\n')] : pieces;
  if (!replies.length) throw new Error('Gemini returned no visible text');
  return {text: replies.join('\n\n'), replies};
}

function signature(ticket) {
  return createHmac('sha256', TELEGRAM_BOT_TOKEN).update(ticket).digest();
}

async function confirmLead(ticket, proof, res) {
  if (!TELEGRAM_BOT_TOKEN || !TELEGRAM_CHAT_ID) return res.status(503).json({error: 'Telegram unavailable'});
  const supplied = Buffer.from(typeof proof === 'string' ? proof : '', 'base64url');
  if (typeof ticket !== 'string' || ticket.length > 32000 || supplied.length !== 32 ||
      !timingSafeEqual(signature(ticket), supplied)) return res.status(400).json({error: 'Invalid draft'});
  const {text, expires} = JSON.parse(ticket);
  if (expires <= Date.now()) return res.status(410).json({error: 'Draft expired'});
  try {
    const response = await fetch('https://api.telegram.org/bot' + TELEGRAM_BOT_TOKEN + '/sendMessage', {
      method: 'POST',
      headers: {'Content-Type':'application/json'},
      body: JSON.stringify({chat_id: TELEGRAM_CHAT_ID, text}),
      signal: AbortSignal.timeout(8000)
    });
    const result = await response.json();
    if (!response.ok || !result.ok) return res.status(502).json({error:'Telegram rejected delivery'});
    return res.status(200).json({sent:true});
  } catch {
    return res.status(502).json({error:'Delivery unconfirmed'});
  }
}

// Recognize direct address in visitor turns only.
const greeting = /^(?:прив[іе]т|вітаю|хай|здоров|здравствуй|добрий (?:день|вечір|ранок)|добрый (?:день|вечер))\s*[,!:.–-]?\s*/iu;
function addressText(text) {
  return text.normalize('NFC').trim().toLowerCase();
}
function callsJack(text) {
  const line = addressText(text);
  const afterHello = line.replace(greeting, '');
  return /^джек(?:у)?(?=$|[\s]*[,!.?:…–-])/u.test(afterHello)
    || /^джек(?:у)?\s+(?:прив[іе]т|помоги|допоможи|скажи|слухай|слушай)(?=$|[^\p{L}])/u.test(afterHello)
    || /,\s*джек(?:у)?\s*[!.?…]*$/u.test(line);
}
function greetingForMax(text) {
  const line = addressText(text).replace(/[,.!?…]+/gu, ' ').trim().replace(/\s+/gu, ' ');
  if (/^(?:привет джек(?:у)?|джек(?:у)? привет)$/u.test(line)) return 'Привет, Макс!';
  if (/^(?:привіт джек(?:у)?|джек(?:у)? привіт|вітаю джек(?:у)?|джек(?:у)? вітаю)$/u.test(line)) return 'Привіт, Максе!';
  return null;
}

